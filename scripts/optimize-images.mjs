import { createHash } from 'node:crypto'
import { createServer as createHttpServer } from 'node:http'
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { chromium } from 'playwright'
import { createServer } from 'vite'

// Rebuild derivatives from the selected real photos; never overwrite originals.
const modules = await createServer({ envFile: false, logLevel: 'error', appType: 'custom', cacheDir: 'node_modules/.cache/image-modules', server: { middlewareMode: true, hmr: false, watch: null } })
let selected
try {
  const { assets, aboutGallery } = await modules.ssrLoadModule('/src/data/assets.ts')
  const { serviceDetailPages } = await modules.ssrLoadModule('/src/data/serviceDetails.ts')
  selected = [...new Set([...Object.values(assets).filter(Boolean), ...aboutGallery.map(image => image.src), ...serviceDetailPages.flatMap(page => page.blocks.map(block => block.image.src))])]
} finally { await modules.close() }

const root = resolve('public')
const server = createHttpServer(async (request, response) => {
  const pathname = decodeURIComponent(new URL(request.url, 'http://localhost').pathname)
  if (pathname === '/') { response.end('<!doctype html><title>Image conversion</title>'); return }
  const file = resolve(root, `.${pathname}`)
  if (!file.startsWith(`${root}\\`) && !file.startsWith(`${root}/`)) { response.writeHead(403).end(); return }
  try { response.end(await readFile(file)) } catch { response.writeHead(404).end() }
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const origin = `http://127.0.0.1:${server.address().port}`
const browser = await chromium.launch({ headless: true })
const variants = {}
const inventory = []
try {
  const page = await browser.newPage()
  await page.goto(origin)
  for (const entry of await readdir(join(root, 'images'), { recursive: true })) {
    if (!/\.(jpe?g|png|webp|avif)$/i.test(entry) || entry.startsWith('optimized')) continue
    const src = `/images/${entry.replaceAll('\\', '/')}`
    const bytes = (await stat(join(root, 'images', entry))).size
    const dimensions = await page.evaluate(async src => {
      const image = new Image(); image.src = src
      try { await image.decode(); return { width: image.naturalWidth, height: image.naturalHeight } } catch { return { invalid: true } }
    }, src)
    inventory.push({ src, bytes, ...dimensions, selected: selected.includes(src) })
  }
  await mkdir(join(root, 'images/optimized'), { recursive: true })
  for (const src of selected) {
    const sourceBytes = await readFile(join(root, src))
    const hash = createHash('sha256').update(sourceBytes).digest('hex').slice(0, 12)
    const converted = await page.evaluate(async src => {
      const image = new Image(); image.src = src; await image.decode()
      const widths = [...new Set([400, 800, Math.min(1280, image.naturalWidth)].filter(width => width <= image.naturalWidth))].sort((a, b) => a - b)
      return widths.map(width => {
        const canvas = document.createElement('canvas'); canvas.width = width; canvas.height = Math.round(width * image.naturalHeight / image.naturalWidth)
        canvas.getContext('2d').drawImage(image, 0, 0, canvas.width, canvas.height)
        return { width, height: canvas.height, base64: canvas.toDataURL('image/webp', 0.86).split(',')[1] }
      })
    }, src)
    variants[src] = []
    for (const variant of converted) {
      const target = `/images/optimized/${hash}-${variant.width}.webp`
      const buffer = Buffer.from(variant.base64, 'base64')
      await writeFile(join(root, target), buffer)
      variants[src].push({ src: target, width: variant.width, height: variant.height, bytes: buffer.length })
    }
  }
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)) }
await writeFile('src/data/imageVariants.ts', `// Generated by node scripts/optimize-images.mjs from preserved source photographs.\nexport const imageVariants: Record<string, readonly { src: string; width: number; height: number; bytes: number }[]> = ${JSON.stringify(variants, null, 2)}\n`)
await mkdir('reports/prelaunch', { recursive: true })
await writeFile('reports/prelaunch/images.json', JSON.stringify({ inventory, variants }, null, 2))
const sourceTotal = inventory.filter(image => image.selected).reduce((sum, image) => sum + image.bytes, 0)
const largestTotal = Object.values(variants).reduce((sum, images) => sum + images.at(-1).bytes, 0)
console.log(`${inventory.length} source images inspected; ${selected.length} selected sources; largest WebP variants ${largestTotal} bytes vs ${sourceTotal} source bytes (${Math.round(100 * (1 - largestTotal / sourceTotal))}% smaller).`)
